import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { issueSession, verifySession } from './native-session-boundary.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'hmw-auth-boundary-'));
const key = randomBytes(32), now = Date.now();
for (const slot of ['t1', 't2']) fs.mkdirSync(path.join(root, slot));
fs.mkdirSync(path.join(root, 't1', 'alice'));
fs.symlinkSync(path.join(root, 't1', 'alice'), path.join(root, 't2', 'alice'));
const issue = (changes = {}) => issueSession({ authenticatedSubject: 'alice', slot: 't1', secret: key, now, ...changes });
const verify = (credential, changes = {}) => verifySession({ credential, slot: 't1', secret: key, now, workspaceRoot: root, ...changes });
test('server-issued session resolves its own workspace', () => assert.equal(verify(issue()).workspace, path.join(root, 't1', 'alice')));
test('rejects missing credential', () => assert.throws(() => verify(), /unauthorized/));
test('rejects cross-slot use', () => assert.throws(() => verify(issue(), { slot: 't2' }), /unauthorized/));
test('rejects symlinked slot session', () => assert.throws(() => verify(issue({ slot: 't2' }), { slot: 't2' }), /unauthorized/));
test('rejects tampered signature', () => assert.throws(() => verify(issue() + 'a'), /unauthorized/));
test('rejects expired token', () => assert.throws(() => verify(issue(), { now: now + 300001 }), /unauthorized/));
test('rejects future issued token', () => assert.throws(() => verify(issue(), { now: now - 1 }), /unauthorized/));
test('rejects path traversal subject', () => assert.throws(() => issue({ authenticatedSubject: '../bob' }), /unauthorized/));
test('rejects missing secret', () => assert.throws(() => issue({ secret: undefined }), /unauthorized/));
test('rejects excessive TTL', () => assert.throws(() => issue({ ttlMs: 3600000 }), /unauthorized/));
test('rejects missing workspace', () => assert.throws(() => verify(issue(), { workspaceRoot: path.join(root, 'missing') }), /unauthorized/));
test('rejects wrong key', () => assert.throws(() => verify(issue(), { secret: randomBytes(32) }), /unauthorized/));
process.on('exit', () => fs.rmSync(root, { recursive: true, force: true }));